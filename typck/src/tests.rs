#![expect(
    clippy::needless_raw_string_hashes,
    reason = "generated by expect-test"
)]

use expect_test::expect;

use crate::{parse, typck::typck};

fn run_typck(input: &str) -> String {
    let program = match parse(input) {
        Err(e) => {
            return format!("-1\nParser error:\n{e}\n");
        }
        Ok(program) => program,
    };
    match typck(&program) {
        Ok(()) => "0".into(),
        Err(e) => format!("{}\n{e}", e.code()),
    }
}

macro_rules! tests {
    ($(
        $name:ident
        $input:literal
        $output:expr
    )+) => {
        $(
            #[test]
            fn $name() {
                $output.assert_eq(&run_typck($input))
            }
        )+
    };
}

